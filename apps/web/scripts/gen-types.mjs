// Generates TypeScript types from the contract JSON Schemas (src/atlas/contracts/schemas).
// Output is committed under src/api/generated/. Never hand-edit those files.
import { compileFromFile } from "json-schema-to-typescript";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemasDir = join(here, "..", "..", "..", "src", "atlas", "contracts", "schemas");
const outDir = join(here, "..", "src", "api", "generated");
mkdirSync(outDir, { recursive: true });

const banner =
  "/* AUTO-GENERATED by `npm run gen:types` from src/atlas/contracts/schemas. Do not edit by hand. */";
const names = [];
for (const file of readdirSync(schemasDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const name = basename(file, ".schema.json");
  const ts = await compileFromFile(join(schemasDir, file), {
    bannerComment: banner,
    additionalProperties: false,
    style: { singleQuote: false },
  });
  writeFileSync(join(outDir, `${name}.ts`), ts);
  names.push(name);
}
const index = [banner, ...names.map((n) => `export type { ${n} } from "./${n}";`), ""].join("\n");
writeFileSync(join(outDir, "index.ts"), index);
console.log(`generated ${names.length} schema type files in ${outDir}`);
